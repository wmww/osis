//! Judgment conformance vectors (core/test/vectors/README.md, `judgment/`): histories played by
//! the order harness (`order::play`), carried in a bundle as one label's host holds them, judged
//! by a fresh node in a given arrival order; the expected verdicts are what this engine judges.
//! `judgment_vectors_*` replays every committed case through a fresh engine and compares, and
//! checks the files equal a fresh generation; `judgment_vectors_write` (ignored) rewrites them.

use crate::order::{Played, Step, play};
use osis_base::{CommitId, Role, Tid, WallMs};
use osis_crypto::{Epoch, LabelRole, Secret32, SeededRng, label_role_key};
use osis_label::{BundleReader, BundleWriter, Importer, Parent, Record, StepKeys, genesis_label, register, sign_stamp};
use osis_node::labeling::{Body, open_commit, seal_body};
use osis_node::local_peer::Peer;
use osis_vectors::file::{Record as Rec, VecFile};
use std::collections::{BTreeMap, BTreeSet};

/// The judging node's rng seed (its own identity is never observed).
const FRESH: u64 = 0x5eed_f00d;
/// Fields of a case that are inputs; every other field is expected output.
const INPUTS: [&str; 7] = ["case", "spec", "source", "read-secret", "now", "bundle", "order"];
const GEN: &str = "generated by `cargo test -p osis-node --test it -- --ignored judgment_vectors_write`; do not edit";

fn s32(b: u8) -> Secret32 {
    Secret32::from_bytes([b; 32])
}

/// One arrival step: ingest bundle entry i, advance the clock by ms and run timers, or drop
/// every aspect of entry i's body as covered (node-sync's compaction drop).
#[derive(Clone, Copy, Debug)]
enum Tok {
    In(usize),
    Wait(u64),
    Drop(usize),
}

fn render_order(o: &[Tok]) -> String {
    o.iter().map(|t| match t {
        Tok::In(i) => i.to_string(),
        Tok::Wait(ms) => format!("+{ms}"),
        Tok::Drop(i) => format!("d{i}"),
    }).collect::<Vec<_>>().join(",")
}

fn parse_order(s: &str) -> Vec<Tok> {
    s.split(',').map(|t| match (t.strip_prefix('+'), t.strip_prefix('d')) {
        (Some(ms), _) => Tok::Wait(ms.parse().unwrap()),
        (_, Some(i)) => Tok::Drop(i.parse().unwrap()),
        _ => Tok::In(t.parse().unwrap()),
    }).collect()
}

/// A played history as one label's bundle: the genesis path (group secrets read `0a`, write
/// `0b`, admin `09`, deposit seed `0c`), then per commit its bodies (`osis_commit::project`, one
/// reader) sealed and stamped, each blob before its entry. Also each entry's commit index.
fn bundle(played: &Played) -> (Vec<u8>, Vec<usize>) {
    let (r, w, a) = (s32(0x0a), s32(0x0b), s32(0x09));
    let label = genesis_label(&a, 0);
    let keys = StepKeys::derive(&r, &w, &a, 0, &s32(0x0c), &label);
    let delete = label_role_key(LabelRole::Delete, &a, 0);
    let mut rng = SeededRng::from_u64(0x0b0d1e);
    let (step, claims) = register(Parent::Genesis(&delete), keys, &[], (&Tid::from_bytes([0x07; 15]), Epoch::new(0, [0; 32]).unwrap(), &r), &mut rng).unwrap();
    let stamp_key = label_role_key(LabelRole::Write, &w, 0);
    let mut recs = vec![Record::Path { label: step.label, steps: vec![(step.clone(), Some(claims))] }];
    let mut of = Vec::new();
    for (ci, pk) in played.packs.iter().enumerate() {
        assert!(pk.blobs.is_empty(), "a referenced blob: not in this format yet");
        let cb = osis_commit::CommitBlob::decode(&pk.bytes).unwrap();
        for p in osis_commit::project(&cb, |_| ()).unwrap() {
            let body = Body { commit: pk.id, reader: Tid::from_bytes([0; 15]), parts: p.parts, expires: p.expires, keys: p.keys, blind: cb.header.blind, plaintext: p.plaintext, role_commit: cb.header.kind.is_role() };
            let sealed = seal_body(&body, &mut rng).unwrap();
            let wrap = osis_crypto::wrap(&r, &sealed.id, &sealed.key).unwrap();
            let stamp = sign_stamp(&stamp_key, &step.label, &sealed.id, &wrap);
            recs.push(Record::Blob(sealed.blob));
            recs.push(Record::Entry { label: step.label, blob: sealed.id, wrap, stamp: Some(stamp) });
            of.push(ci);
        }
    }
    let mut bw = BundleWriter::new(Vec::new()).unwrap();
    for x in &recs {
        bw.record(x).unwrap();
    }
    (bw.finish().unwrap(), of)
}

/// Reads a bundle as an importer does (paths and stamps verified): its entries in order, each
/// with its blob.
fn entries(bytes: &[u8]) -> Vec<(osis_base::BlobId, [u8; osis_crypto::WRAP_LEN], Vec<u8>)> {
    let mut rd = BundleReader::new(bytes).unwrap();
    let mut imp = Importer::new();
    let mut blobs = BTreeMap::new();
    let mut out = Vec::new();
    while let Some(r) = rd.next_record().unwrap() {
        imp.import(r.clone()).unwrap().unwrap();
        match r {
            Record::Blob(b) => {
                blobs.insert(osis_label::blob_id(&b), b);
            }
            Record::Entry { blob, wrap, .. } => out.push((blob, wrap, blobs[&blob].clone())),
            _ => {}
        }
    }
    out
}

fn role(r: Role) -> &'static str {
    match r {
        Role::Read => "read",
        Role::Write => "write",
        Role::Admin => "admin",
    }
}

fn hash_hex(b: &[u8]) -> String {
    osis_base::hex::encode(&osis_base::hash::hash(b))
}

/// The canonical state bytes of a fragment: a snapshot delta (spec/crdt.md §3, §8) with an
/// all-zero nonce, no frontiers or absorbed, `ts` 0, own source `Commit(0^32)`, unpaged.
fn state_bytes(f: &osis_crdt::Fragment) -> Vec<u8> {
    let snap = osis_crdt::Snapshot { nonce: [0; 16], fragment: f.clone(), frontiers: Default::default(), absorbed: Default::default() };
    let cx = osis_crdt::DeltaCtx { ts: osis_base::Ts::default(), own: osis_crdt::Source::commit(CommitId([0; 32])), range: osis_crdt::CounterRange::EMPTY, kind: osis_crdt::DeltaKind::Snapshot };
    osis_crdt::encode_snapshot(&snap, &cx, None).unwrap()
}

/// Delivers `order` of the bundle's entries to a fresh node at `now`; what it judges, as the
/// expected fields of a case (README.md, `judgment/`).
fn replay(bytes: &[u8], read: &Secret32, now: WallMs, order: &[Tok]) -> Vec<(String, String)> {
    let ents = entries(bytes);
    let mut p = Peer::new(FRESH, now).unwrap();
    let mut ids = BTreeSet::new();
    let open = |i: usize| {
        let (id, wrap, blob) = &ents[i];
        let (_, key) = osis_label::unwrap_any([read], id, wrap).unwrap();
        open_commit(blob, &key).unwrap()
    };
    for t in order {
        match *t {
            Tok::In(i) => {
                let (pt, cb) = open(i);
                ids.insert(cb.id());
                let _ = p.engine.ingest(&pt, Vec::new());
            }
            Tok::Wait(ms) => {
                p.clock.advance(ms);
                p.engine.tick().unwrap();
            }
            Tok::Drop(i) => {
                let (_, cb) = open(i);
                for part in &cb.parts {
                    let a = &cb.header.aspects[part.ai];
                    p.engine.drop_body(&cb.id(), &a.tid, &a.ak).unwrap();
                }
            }
        }
    }
    observe(&mut p.engine, &ids)
}

fn observe(e: &mut osis_node::Engine, ids: &BTreeSet<CommitId>) -> Vec<(String, String)> {
    let hex = |c: &CommitId| osis_base::hex::encode(&c.0);
    let dig = e.index_digest();
    let mut held: Vec<(osis_base::Ts, CommitId)> = ids.iter().filter_map(|c| e.header(c).map(|h| (h.ts, *c))).collect();
    held.sort();
    let mut out = Vec::new();
    let mut things = BTreeSet::new();
    let mut aspects = BTreeSet::new();
    for (_, c) in &held {
        let h = e.header(c).unwrap();
        let d = &dig.commits[c];
        for (ai, a) in h.aspects.iter().enumerate() {
            things.insert(a.tid);
            aspects.insert((a.tid, a.ak.clone()));
            let valid = if e.body_valid(c, &a.tid, &a.ak).unwrap() { "valid" } else { "invalid" };
            let status = if d.missing.contains(&ai) {
                "missing"
            } else if d.dropped.contains(&ai) {
                "dropped"
            } else {
                "held"
            };
            let mut v = format!("{valid} {status}");
            if status == "held" {
                let mut by = Vec::new();
                for (_, s) in &held {
                    let sh = e.header(s).unwrap();
                    if s != c && sh.kind.is_compaction() && sh.aspects.iter().any(|x| x.tid == a.tid && x.ak == a.ak) && e.covered(s, c, &a.tid, &a.ak).unwrap() == Some(true) {
                        by.push(hex(s));
                    }
                }
                v += &format!(" covered-by={}", if by.is_empty() { "-".to_string() } else { by.join(",") });
            }
            if a.retention.at_least.rel.is_some() || a.retention.at_most.rel.is_some() {
                v += &match e.deaths(c, &a.tid, &a.ak).unwrap() {
                    Some((x, y)) => format!(" deaths={},{}", x.to_u64(), y.to_u64()),
                    None => " deaths=none".into(),
                };
            }
            out.push((format!("body {} {} {}", hex(c), a.tid, a.ak.as_str()), v));
        }
    }
    let mut pending: Vec<String> = e.pending().into_iter().map(|x| x.0).filter(|c| ids.contains(c)).map(|c| hex(&c)).collect();
    pending.sort();
    out.push(("waiting".into(), if pending.is_empty() { "-".into() } else { pending.join(",") }));
    for t in &things {
        let start = e.epoch_start(t).map_or("-".to_string(), |c| hex(&c));
        let roster: Vec<String> = e.roster(t).iter().map(|(h, ed)| {
            let mut s = format!("{h}:{}", role(ed.role));
            if let Some(u) = ed.until {
                s += &format!(":until={}", u.0);
            }
            if let Some(i) = ed.invite {
                s += &format!(":invite={}", role(i));
            }
            s
        }).collect();
        out.push((format!("thing {t}"), format!("start={start} roster={}", roster.join(","))));
    }
    let key = |c: &CommitId| e.header(c).map(|h| (h.ts, h.author));
    let mut drops: Vec<_> = e.drop_set().into_iter().filter(|(w, _, _)| ids.contains(&w.commit())).collect();
    drops.sort_by_key(|(w, p, edge)| ((p.ts, p.node, p.commit), key(&w.commit()), w.commit(), *edge));
    // a commit's ops on one edge count once
    drops.dedup_by_key(|(w, p, edge)| (w.commit(), p.commit, *edge, matches!(w, osis_perm::WriteId::Snapshot(_))));
    for (n, (w, p, edge)) in drops.iter().enumerate() {
        let what = match edge {
            Some((t, h)) => format!("{} {t} {h}", hex(&w.commit())),
            None => format!("{} snapshot", hex(&w.commit())),
        };
        out.push((format!("drop {n}"), format!("{what} by {}", hex(&p.commit))));
    }
    for (t, a) in &aspects {
        let state = e.state(t, a).unwrap().map_or("absent".to_string(), |f| hash_hex(&state_bytes(&f)));
        let read = e.get(t, a).unwrap().map_or("absent".to_string(), |v| hash_hex(&osis_base::encode(&v)));
        out.push((format!("aspect {t} {}", a.as_str()), format!("state={state} read={read}")));
    }
    out
}

/// Named arrival orders from each entry's commit index and the setup's commit count.
type OrdersFn = fn(&[usize], usize) -> Vec<(&'static str, Vec<Tok>)>;

/// A history and the arrival orders it is judged in.
struct Scenario {
    name: &'static str,
    spec: &'static str,
    source: &'static str,
    seed: u64,
    steps: Vec<Step>,
    /// Orders by entry, given each entry's commit index and the setup's commit count; `None`:
    /// as made, and the setup first with the rest reversed.
    orders: Option<OrdersFn>,
}

fn default_orders(of: &[usize], base: usize) -> Vec<(&'static str, Vec<Tok>)> {
    let made: Vec<Tok> = (0..of.len()).map(Tok::In).collect();
    let k = of.iter().position(|c| *c >= base).unwrap_or(of.len());
    let rev = (0..k).chain((k..of.len()).rev()).map(Tok::In).collect();
    vec![("as made", made), ("reversed", rev)]
}

fn generate(spec: &str, scenarios: Vec<Scenario>) -> VecFile {
    let header = Rec::new().with("subject", "judgment").with("spec", spec).with("source", GEN);
    let mut cases = Vec::new();
    let now_of = |p: &Played| p.now.0.to_string();
    for sc in scenarios {
        let played = play(sc.seed, &sc.steps);
        let (bytes, of) = bundle(&played);
        let orders = sc.orders.unwrap_or(default_orders)(&of, played.base);
        let first = format!("{}, {}", sc.name, orders[0].0);
        for (i, (oname, order)) in orders.into_iter().enumerate() {
            let name = format!("{}, {oname}", sc.name);
            let mut r = Rec::new().with("case", &name).with("spec", sc.spec).with("source", sc.source).with("read-secret", osis_base::hex::encode(&[0x0a; 32])).with("now", now_of(&played));
            r = if i == 0 { r.with("bundle", osis_base::hex::encode(&bytes)) } else { r.with("bundle", format!("as in {first}")) };
            r = r.with("order", render_order(&order));
            for (k, v) in replay(&bytes, &s32(0x0a), played.now, &order) {
                r = r.with(&k, v);
            }
            cases.push(r);
        }
    }
    VecFile { header, cases }
}

fn files() -> Vec<(&'static str, String)> {
    vec![
        ("judgment/models.vec", generate("spec/permissions.md §5-§6", models()).render()),
        ("judgment/rules.vec", generate("spec/permissions.md §5-§6, spec/commits.md §5", rules()).render()),
    ]
}

