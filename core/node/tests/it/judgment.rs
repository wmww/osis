/// Replays every case of a committed file (its inputs only) and compares the expected fields.
fn replay_file(path: &str, text: &str) -> Result<usize, String> {
    let f = VecFile::parse(text).map_err(|e| format!("{path}: {e}"))?;
    let mut bundles: BTreeMap<String, Vec<u8>> = BTreeMap::new();
    for c in f.live() {
        let name = c.req("case")?;
        let b = c.req("bundle")?;
        let bytes = match b.strip_prefix("as in ") {
            Some(other) => bundles.get(other).cloned().ok_or_else(|| format!("{name}: no case {other}"))?,
            None => osis_base::hex::decode(b).ok_or_else(|| format!("{name}: bad bundle hex"))?,
        };
        bundles.insert(name.to_string(), bytes.clone());
        let read = osis_base::hex::decode(c.req("read-secret")?).ok_or("bad read-secret")?;
        let read = Secret32::from_bytes(read.try_into().map_err(|_| "read-secret length")?);
        let now = WallMs(c.req("now")?.parse().map_err(|_| "bad now")?);
        let got = replay(&bytes, &read, now, &parse_order(c.req("order")?));
        let want: Vec<(String, String)> = c.fields.iter().filter(|(k, _)| !INPUTS.contains(&k.as_str())).cloned().collect();
        if got != want {
            let first = got.iter().zip(&want).find(|(g, w)| g != w).map(|(g, w)| format!("want `{}: {}`, got `{}: {}`", w.0, w.1, g.0, g.1)).unwrap_or_else(|| format!("{} fields expected, {} judged", want.len(), got.len()));
            return Err(format!("{path}, case `{name}`: {first}"));
        }
    }
    Ok(f.live().count())
}

// spec/permissions.md §5-§6, spec/commits.md §5: every judgment vector (core/test/vectors,
// `judgment/`) replayed through a fresh engine judges as written, and the files are what the
// generator writes now.
#[test]
fn judgment_vectors_spec_permissions_5_2() {
    for (path, fresh) in files() {
        let text = std::fs::read_to_string(osis_vectors::root().join(path)).unwrap();
        let n = replay_file(path, &text).unwrap_or_else(|e| panic!("{e}"));
        assert!(n > 0, "{path}: no cases");
        assert!(fresh == text, "{path}: differs from a fresh generation; rewrite with `cargo test -p osis-node --test it -- --ignored judgment_vectors_write` if the change is meant (a spec change)");
    }
}

