impl Handled {
    /// Has the event been handled yet?
    pub fn is_handled(self) -> bool {
        self == Self::Yes
    }
}

impl From<bool> for Handled {
    /// Returns `Handled::Yes` if `handled` is true, and `Handled::No` otherwise.
    fn from(handled: bool) -> Self {
        if handled { Self::Yes } else { Self::No }
    }
}

// --- MARK: WINIT EXPIES

/// Describes [input method](https://en.wikipedia.org/wiki/Input_method) events.
///
/// Most keypresses using a latin-like keyboard layout simply generate a [`TextEvent::Keyboard`].
/// Input methods (soft keyboards, accent dead keys, pinyin and other candidate pickers) instead
/// edit the focused widget's text directly: each change is an [`Ime::Edit`], a [`TextEdit`] made
/// by the platform shell against the widget's text as [`ImeText`](crate::core::ImeText) shows it
/// (`crate::core::text_input` has the model).
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
pub enum Ime {
    /// The input method was enabled for the focused widget.
    Enabled,

    /// An input method changed the text, selection or composing region.
    Edit(TextEdit),

    /// The input method was disabled. A widget ends any composition, keeping its text.
    Disabled,
}

/// Defines the orientation that a window resize will be performed.
///
/// Mirrors [`winit::window::ResizeDirection`](https://docs.rs/winit/latest/x86_64-unknown-linux-gnu/winit/window/enum.ResizeDirection.html).
#[derive(Debug, Copy, Clone, PartialEq, Eq, Hash)]
#[expect(missing_docs, reason = "Copied from winit")]
pub enum ResizeDirection {
    East,
    North,
    NorthEast,
    NorthWest,
    South,
    SouthEast,
    SouthWest,
    West,
}
