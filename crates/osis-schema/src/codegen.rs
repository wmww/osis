//! Code generation from a schema (plans/schema.md): plain Rust structs and enums with `Codec`
//! (`codec_struct!` for structs), `TryFrom<&Value>` through the schema's typed read, field and
//! case constants for paths, one `Aspect<T>`/`Signal<T>` constant per declared AK and signal kind.
//! Usable from `build.rs` (`generate`) or the `osis-schema-gen` binary.
//!
//! Mapping: string, text, markdown → `String`; blob → `Vec<u8>`; int, timestamp, duration →
//! `i64`; float → `Float` (bit pattern, so every generated type is `Ord`); tid → `Tid`;
//! any → `Value`; option → `Option`; list, set, map → `Vec`, `BTreeSet`, `BTreeMap`; wrappers →
//! their inner type; a recursive type outside a collection is boxed. Inline structs and enums
//! are named after their position (`NoteTyping`, `BoxSealed`).

use crate::error::Error;
use crate::schema::Schema;
use crate::types::Type;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write;

/// Generated source and warnings (the `list<struct>` warning of notes/api.md).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Generated {
    pub code: String,
    pub warnings: Vec<String>,
}

const P: &str = "osis_schema";

/// Generates Rust for `schema`, parsed from `src` (embedded so the generated code carries its
/// schema); `file` names it.
pub fn generate(schema: &Schema, file: &str, src: &str) -> Result<Generated, Error> {
    let mut g = Gen { out: String::new(), items: Vec::new(), names: BTreeSet::new(), recursive: recursive_types(schema), warnings: Vec::new() };
    for name in schema.types.keys() {
        g.names.insert(camel(name));
    }
    let _ = writeln!(g.out, "// Generated by osis-schema-gen from {file}. Do not edit.\n");
    let _ = writeln!(g.out, "/// The schema this module was generated from.");
    let _ = writeln!(g.out, "pub static SCHEMA: {P}::StaticSchema = {P}::StaticSchema::new({file:?}, {src:?});\n");
    for (name, def) in &schema.types {
        g.items.push(Item { rust: camel(name), schema_name: Some(name.clone()), params: def.params.clone(), body: def.body.clone(), doc: def.doc.clone() });
    }
    let prefix = common_namespace(schema.aspects.keys().chain(schema.signals.keys()));
    let mut consts = String::new();
    for (ak, def) in &schema.aspects {
        let cname = const_name(ak, prefix.as_deref());
        let t = g.rust_type(&def.ty, &camel(&cname.to_lowercase()), false)?;
        if let Some(d) = &def.doc {
            doc_lines(&mut consts, d, "");
        }
        let _ = writeln!(consts, "pub const {cname}: {P}::Aspect<{t}> = {P}::Aspect::new({ak:?}, &SCHEMA);");
        if let Ok(Type::List(e)) = schema.expand(&def.ty).as_deref()
            && matches!(schema.expand(e).as_deref(), Ok(Type::Struct(_)))
        {
            g.warnings.push(format!(
                "aspect {ak}: list<struct>: concurrent edits of one record can pair with the wrong element; prefer map<K, struct> or path ops (notes/api.md)"
            ));
        }
    }
    for (kind, def) in &schema.signals {
        let cname = const_name(kind, prefix.as_deref());
        let t = g.rust_type(&def.ty, &camel(&cname.to_lowercase()), false)?;
        if let Some(d) = &def.doc {
            doc_lines(&mut consts, d, "");
        }
        let _ = writeln!(consts, "pub const {cname}: {P}::Signal<{t}> = {P}::Signal::new({kind:?}, &SCHEMA);");
    }
    // Items may queue further inline items while being emitted.
    let mut i = 0;
    while let Some(item) = g.items.get(i).cloned() {
        g.item(&item)?;
        i += 1;
    }
    g.out.push_str(&consts);
    Ok(Generated { code: g.out, warnings: g.warnings })
}

/// Reads, parses, checks against `<file>.lock` when present, and generates.
pub fn generate_file(path: &std::path::Path) -> Result<Generated, Error> {
    let src = std::fs::read_to_string(path).map_err(|e| Error::Io(format!("{}: {e}", path.display())))?;
    let file = path.file_name().map(|f| f.to_string_lossy().into_owned()).unwrap_or_default();
    let schema = crate::parse(&file, &src)?;
    let lock_path = path.with_file_name(format!("{file}.lock"));
    if let Ok(text) = std::fs::read_to_string(&lock_path) {
        crate::check_lock(&schema, &crate::Lock::parse(&text)?, &[])?;
    }
    generate(&schema, &file, &src)
}

#[derive(Clone)]
struct Item {
    rust: String,
    /// Name in the schema (for `TryFrom` through the typed read); `None` for inline items.
    schema_name: Option<String>,
    params: Vec<String>,
    body: Type,
    doc: Option<String>,
}

struct Gen {
    out: String,
    items: Vec<Item>,
    names: BTreeSet<String>,
    recursive: BTreeSet<String>,
    warnings: Vec<String>,
}

impl Gen {
    /// Rust type for `ty`; inline structs and enums become items named `hint`.
    fn rust_type(&mut self, ty: &Type, hint: &str, in_collection: bool) -> Result<String, Error> {
        Ok(match ty {
            Type::String | Type::Text => "String".into(),
            Type::Blob => "Vec<u8>".into(),
            Type::Bool => "bool".into(),
            Type::Int => "i64".into(),
            Type::Float => format!("{P}::osis_core::Float"),
            Type::Tid => format!("{P}::osis_core::Tid"),
            Type::Any => format!("{P}::osis_core::Value"),
            Type::Counter(i) | Type::Max(i) | Type::Min(i) => self.rust_type(i, hint, in_collection)?,
            Type::List(e) => format!("Vec<{}>", self.rust_type(e, hint, true)?),
            Type::Set(e) => format!("std::collections::BTreeSet<{}>", self.rust_type(e, hint, true)?),
            Type::Map(k, v) => {
                format!("std::collections::BTreeMap<{}, {}>", self.rust_type(k, &format!("{hint}Key"), true)?, self.rust_type(v, hint, true)?)
            }
            Type::Param(p) => p.clone(),
            Type::Named(n, args) => match (n.as_str(), args.as_slice()) {
                ("option", [t]) => format!("Option<{}>", self.rust_type(t, hint, in_collection)?),
                ("markdown", []) => "String".into(),
                ("timestamp" | "duration", []) => "i64".into(),
                _ => {
                    let mut s = camel(n);
                    if !args.is_empty() {
                        let a = args.iter().map(|t| self.rust_type(t, hint, true)).collect::<Result<Vec<_>, _>>()?;
                        s = format!("{s}<{}>", a.join(", "));
                    }
                    if self.recursive.contains(n) && !in_collection { format!("Box<{s}>") } else { s }
                }
            },
            Type::Struct(_) | Type::Enum(_) => {
                let rust = hint.to_string();
                if !self.names.insert(rust.clone()) {
                    return Err(Error::Codegen(format!("generated name {rust} collides; name the inline type")));
                }
                // Parameters in scope stay generic parameters of the inline item.
                let params = params_in(ty);
                let s = if params.is_empty() { rust.clone() } else { format!("{rust}<{}>", params.join(", ")) };
                self.items.push(Item { rust, schema_name: None, params, body: ty.clone(), doc: None });
                s
            }
        })
    }

    fn item(&mut self, it: &Item) -> Result<(), Error> {
        let generics = if it.params.is_empty() { String::new() } else { format!("<{}>", it.params.join(", ")) };
        let bounds = if it.params.is_empty() {
            String::new()
        } else {
            format!("<{}>", it.params.iter().map(|p| format!("{p}: {P}::Codec")).collect::<Vec<_>>().join(", "))
        };
        let derive = "#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]";
        // Structs and enums become items; anything else (aliases included) a type alias.
        let body = it.body.clone();
        let mut s = String::new();
        if let Some(d) = &it.doc {
            doc_lines(&mut s, d, "    ");
        }
        match &body {
            Type::Struct(st) => {
                let _ = writeln!(self.out, "{P}::codec_struct! {{");
                self.out.push_str(&s);
                let _ = writeln!(self.out, "    {derive}\n    pub struct {}{generics} {{", it.rust);
                let mut consts = String::new();
                for (id, f) in &st.fields {
                    let t = self.rust_type(&f.ty, &format!("{}{}", it.rust, camel(&f.name)), false)?;
                    if let Some(d) = &f.doc {
                        doc_lines(&mut self.out, d, "        ");
                    }
                    let _ = writeln!(self.out, "        {id} {}: {t},", field_ident(&f.name));
                    let _ = writeln!(consts, "    pub const {}: {P}::FieldId = {P}::FieldId({id});", f.name.to_uppercase());
                }
                let _ = writeln!(self.out, "    }}\n}}");
                let _ = writeln!(self.out, "/// Field IDs of `{}`.\npub mod {} {{\n{consts}}}", it.rust, snake(&it.rust));
            }
            Type::Enum(en) => {
                self.out.push_str(&s.replace("    ///", "///"));
                let _ = writeln!(self.out, "{derive}\npub enum {}{generics} {{", it.rust);
                let (mut to, mut from, mut consts) = (String::new(), String::new(), String::new());
                for (id, c) in &en.cases {
                    let v = camel(&c.name);
                    if let Some(d) = &c.doc {
                        doc_lines(&mut self.out, d, "    ");
                    }
                    match &c.payload {
                        None => {
                            let _ = writeln!(self.out, "    {v},");
                            let _ = writeln!(to, "            {}::{v} => {P}::codec::rt::enum_value({id}, None),", it.rust);
                            let _ = writeln!(from, "            {P}::codec::rt::Value::Enum({id}, None) => Ok({}::{v}),", it.rust);
                        }
                        Some(p) => {
                            let t = self.rust_type(p, &format!("{}{v}", it.rust), false)?;
                            let _ = writeln!(self.out, "    {v}({t}),");
                            let _ = writeln!(to, "            {}::{v}(x) => {P}::codec::rt::enum_value({id}, Some({P}::Codec::to_value(x))),", it.rust);
                            let _ = writeln!(from, "            {P}::codec::rt::Value::Enum({id}, p) => {P}::codec::rt::payload({id}, p).map({}::{v}),", it.rust);
                        }
                    }
                    let _ = writeln!(consts, "    pub const {}: {P}::CaseId = {P}::CaseId({id});", c.name.to_uppercase());
                }
                let _ = writeln!(self.out, "}}");
                let _ = writeln!(
                    self.out,
                    "impl{bounds} {P}::Codec for {}{generics} {{\n    fn to_value(&self) -> {P}::codec::rt::Value {{\n        match self {{\n{to}        }}\n    }}\n    fn from_value(v: &{P}::codec::rt::Value) -> Result<Self, {P}::PathError> {{\n        match v {{\n{from}            _ => Err({P}::codec::rt::unknown_case(v)),\n        }}\n    }}\n}}",
                    it.rust
                );
                let _ = writeln!(self.out, "/// Case IDs of `{}`.\npub mod {} {{\n{consts}}}", it.rust, snake(&it.rust));
            }
            _ => {
                let t = self.rust_type(&body, &it.rust, false)?;
                self.out.push_str(&s.replace("    ///", "///"));
                let _ = writeln!(self.out, "pub type {}{generics} = {t};", it.rust);
            }
        }
        if let (Some(name), true) = (&it.schema_name, it.params.is_empty() && matches!(body, Type::Struct(_) | Type::Enum(_))) {
            let _ = writeln!(
                self.out,
                "impl TryFrom<&{P}::osis_core::Value> for {r} {{\n    type Error = {P}::PathError;\n    /// Typed read through the schema (reader defaults, open structs), then into `{r}`.\n    fn try_from(v: &{P}::osis_core::Value) -> Result<{r}, {P}::PathError> {{\n        let n = {P}::typed_read(SCHEMA.get(), v, &{P}::Type::named({name:?}))?;\n        {P}::Codec::from_value(&n)\n    }}\n}}\nimpl From<&{r}> for {P}::osis_core::Value {{\n    fn from(t: &{r}) -> {P}::osis_core::Value {{\n        {P}::Codec::to_value(t)\n    }}\n}}",
                r = it.rust
            );
        }
        self.out.push('\n');
        Ok(())
    }
}

/// Parameters mentioned inside a type, in first-use order.
fn params_in(t: &Type) -> Vec<String> {
    fn walk(t: &Type, out: &mut Vec<String>) {
        match t {
            Type::Param(p) if !out.contains(p) => out.push(p.clone()),
            Type::List(e) | Type::Set(e) | Type::Counter(e) | Type::Max(e) | Type::Min(e) => walk(e, out),
            Type::Map(k, v) => {
                walk(k, out);
                walk(v, out);
            }
            Type::Named(_, a) => a.iter().for_each(|x| walk(x, out)),
            Type::Struct(s) => s.fields.values().for_each(|f| walk(&f.ty, out)),
            Type::Enum(e) => e.cases.values().filter_map(|c| c.payload.as_ref()).for_each(|p| walk(p, out)),
            _ => {}
        }
    }
    let mut out = Vec::new();
    walk(t, &mut out);
    out
}

/// Named types that reach themselves outside collections (they need a `Box`).
fn recursive_types(s: &Schema) -> BTreeSet<String> {
    fn refs(t: &Type, out: &mut BTreeSet<String>) {
        match t {
            Type::Named(n, a) => {
                out.insert(n.clone());
                a.iter().for_each(|x| refs(x, out));
            }
            Type::Counter(e) | Type::Max(e) | Type::Min(e) => refs(e, out),
            Type::Struct(st) => st.fields.values().for_each(|f| refs(&f.ty, out)),
            Type::Enum(en) => en.cases.values().filter_map(|c| c.payload.as_ref()).for_each(|p| refs(p, out)),
            _ => {} // collections break the size cycle
        }
    }
    let direct: BTreeMap<&String, BTreeSet<String>> = s
        .types
        .iter()
        .map(|(n, d)| {
            let mut out = BTreeSet::new();
            refs(&d.body, &mut out);
            (n, out)
        })
        .collect();
    let mut rec = BTreeSet::new();
    for start in s.types.keys() {
        let mut stack: Vec<String> = direct.get(start).map(|d| d.iter().cloned().collect()).unwrap_or_default();
        let mut seen = BTreeSet::new();
        while let Some(n) = stack.pop() {
            if &n == start {
                rec.insert(start.clone());
                break;
            }
            if seen.insert(n.clone()) {
                stack.extend(direct.get(&n).into_iter().flatten().cloned());
            }
        }
    }
    rec
}

fn camel(s: &str) -> String {
    let mut out = String::new();
    for part in s.split(|c: char| !c.is_ascii_alphanumeric()).filter(|p| !p.is_empty()) {
        let mut c = part.chars();
        if let Some(f) = c.next() {
            out.push(f.to_ascii_uppercase());
            out.extend(c);
        }
    }
    if out.is_empty() || out.starts_with(|c: char| c.is_ascii_digit()) {
        out.insert(0, 'T');
    }
    out
}

fn snake(camel: &str) -> String {
    let mut out = String::new();
    for (i, c) in camel.chars().enumerate() {
        if c.is_ascii_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    if is_keyword(&out) { format!("{out}_") } else { out }
}

fn is_keyword(s: &str) -> bool {
    matches!(
        s,
        "as" | "break" | "const" | "continue" | "crate" | "else" | "enum" | "extern" | "false" | "fn" | "for" | "if" | "impl" | "in"
            | "let" | "loop" | "match" | "mod" | "move" | "mut" | "pub" | "ref" | "return" | "self" | "Self" | "static" | "struct"
            | "super" | "trait" | "true" | "type" | "unsafe" | "use" | "where" | "while" | "async" | "await" | "dyn" | "abstract"
            | "become" | "box" | "do" | "final" | "macro" | "override" | "priv" | "typeof" | "unsized" | "virtual" | "yield" | "try"
            | "gen"
    )
}

fn field_ident(name: &str) -> String {
    match name {
        "self" | "Self" | "super" | "crate" => format!("{name}_"),
        _ if is_keyword(name) => format!("r#{name}"),
        _ => name.to_string(),
    }
}

/// The first AK segment shared by every key, if any.
fn common_namespace<'a>(keys: impl Iterator<Item = &'a String>) -> Option<String> {
    let mut ns: Option<&str> = None;
    for k in keys {
        let first = k.trim_start_matches('/').split('/').next().unwrap_or("");
        match ns {
            None => ns = Some(first),
            Some(n) if n == first => {}
            Some(_) => return None,
        }
    }
    ns.map(str::to_string)
}

/// `/note/last_opened` → `LAST_OPENED` (namespace dropped when shared).
fn const_name(ak: &str, prefix: Option<&str>) -> String {
    let mut segs: Vec<&str> = ak.trim_start_matches('/').split('/').collect();
    if prefix.is_some() && segs.len() > 1 {
        segs.remove(0);
    }
    let s: String = segs.join("_").chars().map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_uppercase() } else { '_' }).collect();
    if s.starts_with(|c: char| c.is_ascii_digit()) { format!("A_{s}") } else { s }
}

fn doc_lines(out: &mut String, doc: &str, indent: &str) {
    for l in doc.lines() {
        let _ = writeln!(out, "{indent}/// {l}");
    }
}
